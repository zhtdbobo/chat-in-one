const fs = require('fs');
const path = require('path');

// Build a browser script from the installed CommonJS distribution; no bundler is needed.
const libraryDir = path.dirname(require.resolve('highlight.js/lib/core'));
const common = fs.readFileSync(path.join(libraryDir, 'common.js'), 'utf8');
const languages = [...common.matchAll(/registerLanguage\('([^']+)', require\('\.\/languages\/([^']+)'\)\)/g)];
const wrap = source => `(function () { const module = { exports: {} };\n${source}\nreturn module.exports; })()`;
let output = '/* Generated by scripts/build-highlight.js. highlight.js, BSD-3-Clause. See highlight.LICENSE. */\n';
output += `(function () {\nconst hljs = ${wrap(fs.readFileSync(path.join(libraryDir, 'core.js'), 'utf8'))};\n`;
for (const [, name, filename] of languages) {
    output += `hljs.registerLanguage(${JSON.stringify(name)}, ${wrap(fs.readFileSync(path.join(libraryDir, 'languages', filename + '.js'), 'utf8'))});\n`;
}
output += 'window.hljs = hljs;\n})();\n';
const destination = path.join(__dirname, '../src/js/vendor');
fs.mkdirSync(destination, { recursive: true });
fs.writeFileSync(path.join(destination, 'highlight.js'), output);
fs.copyFileSync(path.join(libraryDir, '../LICENSE'), path.join(destination, 'highlight.LICENSE'));
console.log(`Built highlight.js with ${languages.length} languages.`);
